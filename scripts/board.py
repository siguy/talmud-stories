# Gates live in FRAMEWORK.md, which is the file that justifies them. Parsed, not retyped.
GATE_RE = re.compile(r"\*\*Gate: (.+?) — (PROVISIONAL|DERIVED)")
TRACTATES = ["ketubot", "kiddushin", "gittin", "yevamot", "eruvin"]


# ---------------------------------------------------------------- sources

def sh(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True).stdout.strip()


def load_json(rel: str):
    p = ROOT / rel
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text())
    except Exception:
        return None


def gates() -> dict[str, str]:
    """Read each capability's gate from FRAMEWORK.md rather than restating it."""
    txt = (ROOT / "FRAMEWORK.md").read_text()
    found = GATE_RE.findall(txt)
    out = {}
    for cap, (value, kind) in zip(CAPS, found):
        out[cap] = f"{value} · {kind}"
    for cap in CAPS:
        out.setdefault(cap, "not yet defined")
    return out


def goldens() -> dict[str, dict]:
    """Every golden on disk -- iterate TRACTATES, never a shorter hardcoded list.

    Until 2026-09-02 this looped over ("ketubot", "kiddushin") while TRACTATES held five.
    The Gittin golden landed and the coverage matrix printed the Classification cell as
    `⬜` -- "never measured" -- for a file sitting in results/canonical/. The board is the
    thing sessions read to decide what to work on, so an artifact it cannot see may as
    well not exist, and nothing raises: a missing golden and an unlooped tractate produce
    the same blank (Lesson 38 -- absence is quiet).

    `load_json` already returns nothing for a file that is not there, so the guard the
    short list was doing is the one the loop already does.
    """
    out = {}
    for t in TRACTATES:
        d = load_json(f"results/canonical/{t}_canonical.json")
        if not d:
            continue
        stories = [s for pg in d["pages"] for s in pg.get("stories", [])]
        # `accepted` = not NOT_A_STORY, which counts BORDERLINE as accepted. Gittin is
        # the first golden to carry that value and this figure does not distinguish it;
        # the split lives in the golden's own `classification_distribution`.
        accepted = [s for s in stories if s.get("classification") != "NOT_A_STORY"]
        out[t] = {"pages": len(d["pages"]), "entries": len(stories), "accepted": len(accepted)}
    return out


def rulers() -> dict[str, dict]:
    """Same fix, same reason: a ruler for a tractate not in the list was unreadable."""
    out = {}
    for t in TRACTATES:
        d = load_json(f"results/rulers/{t}_ruler.json")
        if d:
            out[t] = d.get("metrics", {})
    return out


def expert_lists() -> dict[str, dict]:
    """
    Expert ground truth on disk, each row sized in ITS OWN units.

    Two shapes live in this directory and they are not interchangeable:

    - a **story list** (`stories[]`), counted by its own `blind` / `counts_for_recall`
      flags and never by raw length (Lesson 29);
    - a **comment harvest** (`remarks[]`) — Jeff's anchored marginal remarks, sorted onto
      the axes. It has no `stories` key at all.

    Reading `d.get("stories", [])` for both printed
    `kiddushin_comments_harvested.json` as **0 parsed · 0 blind · 0 count for recall** in
    a table headed BLIND — i.e. as a ground-truth file holding nothing, when it holds 11
    sentence-level remarks including the 2005 margin note that retired an open question
    with Jeff without our having to spend one of his answers on it.

    Zero because the file is empty and zero because this function did not recognise the
    file are different facts and must print as different facts (Lesson 38). An unknown
    shape is named with its keys rather than sized at zero, so it reads as *unclassified*
    and not as *absent*.
    """
    out = {}
    p = ROOT / "results/expert_lists"
    if not p.exists():
        return out
    for f in sorted(p.glob("*.json")):
        d = load_json(str(f.relative_to(ROOT)))
        if not isinstance(d, dict):
            continue
        row = {"path": str(f.relative_to(ROOT))}
        if "stories" in d:
            # The same two filters `measure_recall_vs_expert_list.load_expert()` applies:
            # drop the duplicate first, THEN count the flags. Counting flags over the raw
            # list prints 91 where the harness's denominator is 90 — the board and the
            # harness must not disagree about the size of the same set.
            #
            # Found twice independently, which is worth recording. #6 found it by noticing
            # that this generated cell said 91 while STATUS.md, the ruler and
            # tests/test_kiddushin_list_parse.py all said 90 — `kiddushin_050` is one story
            # listed twice. #17 found it by re-deriving the denominator from the harness.
            # The generated file was the wrong one both times, which is the whole argument
            # for having exactly one of them. #6 applied the filter to `counts_for_recall`
            # alone; it belongs to `parsed` and `blind` too, so it is applied once, here.
            stories = [s for s in d["stories"] if s.get("duplicate_of") is None]
            row |= {
                "shape": "story_list",
                "parsed": len(stories),
                "blind": sum(1 for s in stories if s.get("blind")),
                "counts_for_recall": sum(
                    1 for s in stories if s.get("counts_for_recall", s.get("blind"))),
                "duplicates_dropped": len(d["stories"]) - len(stories),
            }
        elif "remarks" in d:
            row |= {
                "shape": "comment_harvest",
                "remarks": len(d["remarks"]),
                "comments": d.get("comments"),
            }
        else:
            row |= {"shape": "unrecognised", "keys": sorted(d)[:6]}
        out[f.stem] = row
    return out


def _expert_list_size(d: dict) -> str:
    """The size cell for one expert-list row, in the units that row actually has."""
    if d["shape"] == "story_list":
        dup = f" ({d['duplicates_dropped']} duplicate dropped)" if d.get("duplicates_dropped") else ""
        return (f"{d['parsed']} parsed{dup} · {d['blind']} blind "
                f"· {d['counts_for_recall']} count for recall")
    if d["shape"] == "comment_harvest":
        n = d["remarks"]
        src = f" from {d['comments']} comments" if d.get("comments") else ""
        return f"**{n} anchored remarks**{src} — not a story list, carries no recall denominator"
    return ("**shape not recognised by `board.py`** — top-level keys: "
            + ", ".join(f"`{k}`" for k in d["keys"]))


def items() -> list[dict]:
    out = []
    for d, done in ((ROOT / "work", False), (ROOT / "work/done", True)):
        if not d.exists():
            continue
        for f in sorted(d.glob("*.md")):
            if f.name in ("_TEMPLATE.md", "README.md"):
                continue
            m = re.match(r"^---\n(.*?)\n---\n", f.read_text(), re.S)
            if not m:
                continue
            fm = dict(re.findall(r"^(\w+):[ \t]*(.*)$", m.group(1), re.M))
            listy = lambda k: [x.strip() for x in fm.get(k, "").strip("[]").split(",") if x.strip()]
            out.append({
                "slug": f.stem, "done": done, "path": str(f.relative_to(ROOT)),
                "title": fm.get("title", f.stem),
                "capability": listy("capability"), "tractate": listy("tractate"),
                "blocked_by": listy("blocked_by"), "awaiting": listy("awaiting"),
                "writes": listy("writes"),
                "finding": fm.get("finding", "").strip(),
            })
    return out


# ------------------------------------------------- contention (not ordering)

def overlap(a: list[str], b: list[str]) -> list[str]:
    """Paths two items both write. A trailing `/` means the whole subtree.

    `blocked_by` is the ORDERING graph. This is the CONTENTION graph, and they are not
    the same: two items with no ordering relation between them are shown as concurrently
    runnable whether or not they write the same file. Six such pairs existed among the
    items runnable on 2026-08-31, four of them recommended together as the cheapest next
    steps.
    """
    hits = set()
    for x in a:
        for y in b:
            if x == y or x.startswith(y.rstrip("/") + "/") or y.startswith(x.rstrip("/") + "/"):
                hits.add(x if len(x) >= len(y) else y)
    return sorted(hits)


def collisions(its: list[dict]) -> list[tuple[str, str, list[str]]]:
    """Every pair of OPEN items that write a common path, with the paths."""
    import itertools
    open_items = [i for i in its if not i["done"]]
    out = []
    for a, b in itertools.combinations(sorted(open_items, key=lambda x: x["slug"]), 2):
        shared = overlap(a["writes"], b["writes"])
        if shared:
            out.append((a["slug"], b["slug"], shared))
    return out


def lanes(its: list[dict]) -> list[list[str]]:
    """Group open items so that two items in DIFFERENT lanes never write a common path.

    Connected components of the contention graph. A lane runs serially; lanes run in
    parallel. This is the number of concurrent sessions the work actually supports --
    which is not the number of unblocked items, and never has been.
    """
    open_items = sorted([i for i in its if not i["done"]], key=lambda x: x["slug"])
    parent = {i["slug"]: i["slug"] for i in open_items}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x

    for a, b, _ in collisions(its):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb
    groups: dict[str, list[str]] = {}
    for i in open_items:
        groups.setdefault(find(i["slug"]), []).append(i["slug"])
    return sorted(groups.values(), key=lambda g: (-len(g), g[0]))


def report_lanes() -> int:
    """Print the contention graph. Non-zero exit means at least one pair collides --
    which is information, not a failure: it says those two need one lane, not two."""
    its = items()
    cols = collisions(its)
    undeclared = [i["slug"] for i in its if not i["done"] and not i["writes"]]
    ls = lanes(its)

    print(f"{len([i for i in its if not i['done']])} open items -> "
          f"{len(ls)} lane(s) that can run concurrently\n")
    for n, g in enumerate(ls, 1):
        tag = "SERIAL" if len(g) > 1 else "alone "
        print(f"  lane {n:>2} [{tag}] {len(g)} item(s)")
        for s in g:
            print(f"              {s}")
    if cols:
        # Grouped by the contended path, not by pair: 39 pairs is unreadable and, more to
        # the point, six of them are one file. The path is the thing you act on.
        by_path: dict[str, set[str]] = {}
        for a, b, shared in cols:
            for p in shared:
                by_path.setdefault(p, set()).update((a, b))
        print(f"\n{len(cols)} colliding pair(s) over {len(by_path)} contended path(s):\n")
        for p, slugs in sorted(by_path.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            print(f"  {p}   <- {len(slugs)} items")
            for s in sorted(slugs):
                print(f"      {s}")
            print()
    if undeclared:
        print(f"{len(undeclared)} open item(s) declare no `writes:` -- their collisions "
              f"CANNOT be seen:\n  " + "\n  ".join(undeclared))
        return 1
    return 0


def worktrees() -> list[dict]:
    """In flight, from git — not from anyone remembering to update a status field."""
    out = []
    block: dict = {}
    for line in sh("git", "worktree", "list", "--porcelain").split("\n"):
        if line.startswith("worktree "):
            block = {"path": line.split(" ", 1)[1]}
        elif line.startswith("branch "):
            block["branch"] = line.split("/")[-1]
        elif line == "" and block:
            out.append(block); block = {}
    if block:
        out.append(block)
    for w in out:
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=w["path"],
                               capture_output=True, text=True).stdout.strip()
        # STATE.md and WORK.md are always about to change; counting them would make
        # this generator's own output depend on whether it had just run.
        w["uncommitted"] = len([x for x in dirty.split("\n")
                                if x.strip() and not x.endswith(("STATE.md", "WORK.md"))])
    return out


def jeff_questions() -> list[tuple[str, str]]:
    """Open questions, by slug, from comms/JEFF.md — the one place they live."""
    p = ROOT / "comms/JEFF.md"
    if not p.exists():
        return []
    txt = p.read_text()
    sec = re.search(r"## Open questions(.*?)(?=\n## |\Z)", txt, re.S)
    if not sec:
        return []
    return re.findall(r"^\|\s*`(jeff:[a-z0-9-]+)`\s*\|\s*([^|]+?)\s*\|", sec.group(1), re.M)


def recalls() -> dict:
    """Triage recall per tractate, read from the recall harness's own output.

    `results/<t>_jeff2005_matches.json` (no suffix) is ALWAYS the recall denominator —
    `--expert-filter recall` for a pre-parsed list, the whole document for Ketubot.
    Sensitivity variants carry a suffix and are deliberately not read here, so the cell
    cannot silently change which question it answers.

    This replaces a hardcoded `if t == "ketubot"`, which claimed Kiddushin triage was
    never measured for as long as the value lived only in prose.
    """
    out = {}
    for t in TRACTATES:
        f = ROOT / f"results/recall/{t}_jeff2005_matches.json"
        if not f.exists():
            continue
        rows = json.loads(f.read_text())
        if not rows or "survived_triage" not in rows[0]:
            continue   # pre-2026-08-31 artifact: no triage field, so no cell
        out[t] = {"n": len(rows),
                  "triage": sum(1 for r in rows if r["survived_triage"]) / len(rows),
                  # A story on pages that were all skipped cannot have been proposed,
                  # so `in_detector` implies `survived_triage` and the ratio is a true
                  # conditional. Verified 0 exceptions on both tractates, 2026-08-31.
                  "detection_given_triage": (
                      sum(1 for r in rows if r["in_detector"])
                      / max(sum(1 for r in rows if r["survived_triage"]), 1))}
    return out


# ---------------------------------------------------------------- rendering

def cell(v) -> str:
    return v if v else "⬜"


def render_state() -> str:
    g, r, el, gl, rc = gates(), rulers(), expert_lists(), goldens(), recalls()
    its = items()
    L = [BANNER, "", "# STATE — the instrument panel", "",
         "Generated by `scripts/board.py`. Every value below is read from an artifact on",
         "disk or from git; none is typed. The hand-written companion is",
         "[`STATUS.md`](STATUS.md) — the judgment, the hazards, the *\"treat this as",
         "indicated, not measured\"*. Neither replaces the other.", "",
         "**Every number names its dataset and says BLIND or CIRCULAR.** A cell without",
         "provenance is a bug in the generator (FRAMEWORK §3).", "",
         "## Coverage", "",
         "| | Triage | Detection | Classification | Boundaries | Review | Publication |",
         "|---|---|---|---|---|---|---|"]

    for t in TRACTATES:
        m = r.get(t, {})
        det = m.get("detection", {})
        detection = ""
        if t in rc:
            detection = f"{rc[t]['detection_given_triage']*100:.1f}% B"
        elif det:
            detection = f"{det['recall']*100:.1f}% / {det['recall_strict']*100:.1f}% B"
        # Classification and Boundaries have NO on-disk artifact carrying their
        # current value: they come from evaluate_golden.py and score_boundary_targets.py,
        # which write to a scratch path and are not run here. Typing them in would be the
        # exact drift this generator exists to stop, so the cell says where to look
        # instead of inventing a number. Making these derivable is a real gap, named in
        # the footnote below.
        classif = "STATUS · C" if t in gl else ""
        boundaries = "STATUS" if (ROOT / f"results/rulers/{t}_ruler.json").exists() else ""
        review = f"{len(rounds_for(t))} rounds" if rounds_for(t) else ""
        triage = f"{rc[t]['triage']*100:.1f}% · n={rc[t]['n']} B" if t in rc else ""
        L.append(f"| **{t.title()}** | {cell(triage)} | {cell(detection)} | {cell(classif)} "
                 f"| {cell(boundaries)} | {cell(review)} | ⬜ |")
    L += ["", "`B` = BLIND dataset (can measure recall) · `C` = CIRCULAR (precision only) · "
          "`⬜` = never measured.", "",
          "**Triage** is stories surviving, and **Detection** is recall *given the page",
          "survived triage* — both from `results/recall/*_jeff2005_matches.json`, whose",
          "denominator each cell states. Detection is conditioned because the two",
          "capabilities compose and have separate gates; charging Triage's losses to",
          "Detection as well double-counts them (Lesson 35).", "",
          "The **end-to-end** figure — what the pipeline delivers, `triage x detection` —",
          "is quoted **loose / strict** from `results/rulers/`, or from",
          "`results/recall/<t>_strict.json` for a tractate with no ruler yet:", ""]
    for t in TRACTATES:
        d = r.get(t, {}).get("detection", {})
        if d:
            L.append(f"- {t.title()}: **{d['recall']*100:.1f}% loose / "
                     f"{d['recall_strict']*100:.1f}% strict** on {d['denominator']} stories")
            continue
        # A tractate detected but not yet reviewed has no ruler — its strict figure
        # comes from measure_strict_recall.py, which applies the ruler's own
        # narrowing. Without this the matrix would show only the loose cell, and a
        # bare 100.0% is the exact shape the loose window's over-crediting takes.
        sr = load_json(f"results/recall/{t}_strict.json")
        if sr:
            L.append(f"- {t.title()}: **{sr['recall_loose']*100:.1f}% loose / "
                     f"{sr['recall_strict']*100:.1f}% strict** on {sr['denominator']} "
                     f"stories (no ruler yet — no expert round on this tractate)")
    L += ["",
          "The loose test credits a proposal anywhere in the aligner's window and is",
          "provably over-credited in at least one case, so read it as an upper bound.", "",
          "**Cells reading `STATUS` are a known gap in this generator, not a formatting**",
          "**choice.** Classification and Boundaries have no artifact on disk carrying",
          "their current value — they are produced by `evaluate_golden.py` and",
          "`score_boundary_targets.py`, which write to a scratch path this script does not",
          "read and must not re-run. (Triage left this list on 2026-08-31, when the recall",
          "harness started writing `survived_triage` per story, so the cell became",
          "derivable.) Until those scripts also write a small committed",
          "measurements file, the honest cell is a pointer to the hand-written number in",
          "[`STATUS.md`](STATUS.md), not a number typed into a generator that promises it",
          "types none.", ""]

    for cap in CAPS:
        L += [f"### {CAP_TITLE[cap]}", "```"]
        L.append(f"gate       {g[cap]}")
        hist = f"docs/capabilities/{CAPS.index(cap)+1}_{cap}.md"
        L.append(f"history    {hist}" if (ROOT / hist).exists() else "history    —")
        infl = [i for i in its if cap in i["capability"] and not i["done"]]
        if infl:
            for i in infl[:6]:
                flags = []
                if i["blocked_by"]:
                    flags.append("blocked: " + ", ".join(i["blocked_by"]))
                if i["awaiting"]:
                    flags.append("awaiting: " + ", ".join(i["awaiting"]))
                L.append(f"open       {i['slug']}" + (f"   ← {' · '.join(flags)}" if flags else ""))
        else:
            L.append("open       —")
        done = [i for i in its if cap in i["capability"] and i["done"]]
        L.append(f"closed     {len(done)} item(s) in work/done/")
        L += ["```", ""]

    L += ["## Ground truth on hand", "", "| dataset | kind | size |", "|---|---|---|"]
    for t, d in sorted(el.items()):
        kind = "**BLIND**" if d["shape"] != "unrecognised" else "**UNKNOWN**"
        L.append(f"| `{d['path']}` | {kind} | {_expert_list_size(d)} |")
    for t, d in sorted(gl.items()):
        L.append(f"| `results/canonical/{t}_canonical.json` | **CIRCULAR** | {d['pages']} pages "
                 f"· {d['entries']} entries · {d['accepted']} accepted |")
    for t, m in sorted(r.items()):
        det = m.get("detection", {})
        if det:
            L.append(f"| `results/rulers/{t}_ruler.json` | **JOINED** | denominator "
                     f"{det['denominator']} · found {det['found']} |")
    L += ["", "**Quote entries against entries and accepted against accepted, never one of "
          "each.** This project did exactly that for months.", ""]

    unfolded = unfolded_verdict_files()
    if unfolded:
        L += ["## Expert verdicts on disk that no ruler reads", "",
              "Each of these is a round Jeff gave us whose verdicts are not in any ruler, so",
              "they are invisible to every precision number. Lesson 1's failure, still live.",
              "Counts are measured; files holding zero verdicts are not listed, because",
              "naming an empty file as a lost round buries the one that is not.", ""]
        L += [f"- `validation/feedback/{f}` — **{n} verdicts**" for f, n in unfolded] + [""]

    q = jeff_questions()
    L += ["## Open with Jeff", ""]
    if q:
        L += ["| slug | question |", "|---|---|"] + [f"| `{s}` | {t} |" for s, t in q]
        waiting = [i for i in its if i["awaiting"]]
        if waiting:
            L += ["", "Items that can finish but cannot conclude until he answers:", ""]
            L += [f"- `{i['slug']}` — {', '.join(i['awaiting'])}" for i in waiting]
    else:
        L.append("`comms/JEFF.md` not present or has no open-questions table.")
    return "\n".join(L) + "\n"


def rounds_for(tractate: str) -> list[str]:
    """Review rounds actually folded into the ruler — the authoritative on-disk source.

    Counting verdict files in validation/feedback/ by filename does not work: most are
    named v5_1_feedback_* / canonical_review_* / v8_delta_* and carry no tractate in the
    name. The ruler records exactly which it consumed, so use that.
    """
    d = load_json(f"results/rulers/{tractate}_ruler.json") or {}
    return list((d.get("review_rounds") or {}).keys())


def _verdict_count(path) -> int:
    """
    How many expert verdicts a feedback file actually holds, across both shapes.

    The dict shape (`reviews`/`feedback` keyed "<ref>_<start>-<end>") is what every
    ruler reads. The list shape (`feedback` as a list of {ref, feedback_type, ...})
    is used by the 2026-01-08 round alone and is read by nothing.

    Counting matters because "unconsumed" is not "lost": of the three files this
    used to name, one holds 25 real verdicts, one has an EMPTY validations dict,
    and one is an automated eval trace with no expert judgement in it. Listing all
    three as lost expert work overstated the gap by two (measured 2026-08-31).
    """
    try:
        data = json.loads(path.read_text())
    except Exception:
        return 0
    if not isinstance(data, dict):
        return 0
    items = data.get("reviews") or data.get("feedback") or data.get("validations")
    if isinstance(items, dict):
        return sum(1 for v in items.values()
                   if isinstance(v, dict) and _is_verdict(v))
    if isinstance(items, list):
        return sum(1 for v in items if isinstance(v, dict) and _is_verdict(v))
    return 0


