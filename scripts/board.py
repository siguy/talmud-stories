def body_of(text: str) -> str:
    """The stable part: what the checksum covers and what --check compares.

    The live block is excluded on purpose. It reports the state of every worktree at
    generation time, so including it would make the file permanently 'stale' the moment
    anyone touched anything -- which would train people to ignore the check.
    """
    out, skip = [], False
    for l in text.split("\n"):
        if l.startswith(LIVE_OPEN):
            skip = True
        elif l.startswith(LIVE_CLOSE):
            skip = False
        elif not skip and not l.startswith("<!-- board-checksum:"):
            out.append(l)
    return "\n".join(out)


def stamp(text: str) -> str:
    h = hashlib.sha256(body_of(text).encode()).hexdigest()[:16]
    return text.rstrip("\n") + "\n" + CKSUM.format(h) + "\n"


def write(path: Path, text: str, force: bool, check: bool) -> bool:
    """Returns True if the file is already up to date. Refuses to clobber a hand-edit."""
    new = stamp(text)
    if path.exists():
        old = path.read_text()
        m = re.search(r"<!-- board-checksum: ([0-9a-f]+) -->", old)
        old_body = body_of(old)
        edited = not m or hashlib.sha256(old_body.encode()).hexdigest()[:16] != m.group(1)
        if edited and not force:
            print(f"REFUSING to overwrite {path.name}: it was edited by hand since the last "
                  f"generation.\nReconcile, then re-run with --force.\n")
            for line in list(difflib.unified_diff(
                    old_body.split("\n"), body_of(new).split("\n"),
                    fromfile=f"{path.name} (on disk)", tofile=f"{path.name} (generated)",
                    lineterm=""))[:60]:
                print(" ", line)
            sys.exit(2)
        if body_of(old) == body_of(new):
            return True
    if check:
        return False
    path.write_text(new)
    return False


