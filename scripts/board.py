#!/usr/bin/env python3
"""
board.py — generate STATE.md (the instrument panel) and WORK.md (what is in flight).

Both files are GENERATED. Every value is derived from a real artifact on disk or from
git; nothing is typed. That is the point: this repo has twice carried the same number in
two places and let them drift (FRAMEWORK said the golden was both 182 and 187).

    python3 scripts/board.py                 # regenerate both
    python3 scripts/board.py --check         # exit 1 if either is stale (for CI/tests)
    python3 scripts/board.py lanes           # what can safely run at the same time
    python3 scripts/board.py setup           # one-time per clone: hooks + merge driver
    python3 scripts/board.py capture         # push every worktree's uncommitted work
    python3 scripts/board.py new-tractate gittin

REFUSES TO OVERWRITE A HAND-EDIT. Each generated file embeds a checksum of its own body.
If the body on disk does not match, the file was edited by hand: board.py prints the diff
and exits non-zero rather than silently destroying the edit. `--force` overrides.

Every cell carries its dataset and its BLIND / CIRCULAR flag. A cell without provenance
is a bug in this generator, not a formatting choice (FRAMEWORK §3).

This script never runs a model, never runs evaluate_golden.py, and never writes anywhere
except STATE.md and WORK.md.
"""
